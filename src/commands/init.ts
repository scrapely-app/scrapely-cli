import inquirer from 'inquirer';
import chalk from 'chalk';
import { existsSync, writeFileSync, mkdirSync, readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { safeResolve, validateFilename } from '../utils/pathValidation.js';
import { ACTOR_CONFIG_FILES } from '../config.js';


function validateActorName(input: string): string | boolean {
    if (input.length < 3) {
        return 'The Actor name must be at least 3 characters long.';
    }
    if (!/^[a-z0-9]([a-z0-9-]*[a-z0-9])?$/.test(input)) {
        return 'The Actor name must be a DNS hostname-friendly string (e.g. my-newest-actor).';
    }
    return true;
}

/**
 * Generated for Scrapy projects (detected via scrapy.cfg):
 * wraps the existing spiders so the project can run as a Scrapely Actor.
 */
const SCRAPY_MAIN_PY = `"""
Scrapely Actor entrypoint for an existing Scrapy project.

Generated by 'scrapely init' when a scrapy.cfg file is detected. It runs
the spiders already defined in the project inside the Actor context and
pushes every scraped item to the Actor's default dataset.
"""

import asyncio
import json

from itemadapter import ItemAdapter
from scrapy.crawler import CrawlerProcess
from scrapy.utils.project import get_project_settings

from scrapely import Actor

# Items are pushed to the dataset in batches of this size.
PUSH_BATCH_SIZE = 50


class ScrapelyDatasetPipeline:
    """Scrapy item pipeline that pushes scraped items to the Actor's default dataset."""

    # The Actor's asyncio loop; Scrapy itself runs in a worker thread.
    loop: asyncio.AbstractEventLoop | None = None

    def __init__(self) -> None:
        self._batch: list[dict] = []

    def process_item(self, item, spider):
        # Round-trip through JSON so dates, decimals etc. become plain values.
        self._batch.append(json.loads(json.dumps(ItemAdapter(item).asdict(), default=str)))
        if len(self._batch) >= PUSH_BATCH_SIZE:
            self._flush()
        return item

    def close_spider(self, spider) -> None:
        self._flush()

    def _flush(self) -> None:
        if not self._batch:
            return
        batch, self._batch = self._batch, []
        # Block the crawler thread until the batch is stored (back-pressure).
        asyncio.run_coroutine_threadsafe(Actor.push_data(batch), self.loop).result()


def run_spiders(settings) -> None:
    """Run every spider of the project. Called in a worker thread.

    Scrapy's Twisted reactor needs an event loop of its own (the Actor's loop
    is already running in the main thread) and cannot install signal handlers
    outside the main thread.
    """
    asyncio.set_event_loop(asyncio.new_event_loop())
    process = CrawlerProcess(settings)

    spider_names = process.spider_loader.list()
    if not spider_names:
        raise RuntimeError(
            'No spiders found in the Scrapy project - add one under the spiders/'
            ' directory first.'
        )

    for spider_name in spider_names:
        process.crawl(spider_name)

    process.start(stop_after_crawl=True, install_signal_handlers=False)


async def main() -> None:
    """Run the Scrapy project inside the Actor context."""
    ScrapelyDatasetPipeline.loop = asyncio.get_running_loop()

    settings = get_project_settings()
    pipelines = dict(settings.getdict('ITEM_PIPELINES'))
    # Last in line, so items reach the dataset after the project's own pipelines.
    pipelines[ScrapelyDatasetPipeline] = 1000
    settings.set('ITEM_PIPELINES', pipelines, priority='cmdline')

    await asyncio.to_thread(run_spiders, settings)


if __name__ == '__main__':
    asyncio.run(Actor.main(main))
`;

/** PyPI name of the Scrapely Python SDK (import name: scrapely). */
export const PYPI_SDK_PACKAGE = 'scrapely-python';

/** Requirement name of a requirements.txt line ("pkg[extra]>=1 ; marker" -> "pkg"), or null. */
function requirementName(line: string): string | null {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('-')) return null;
    const m = /^([A-Za-z0-9][A-Za-z0-9._-]*)/.exec(trimmed);
    return m ? m[1].toLowerCase().replace(/[._]/g, '-') : null;
}

/**
 * Make a Scrapy project's requirements.txt install the Scrapely SDK and Scrapy:
 * replaces a bare "scrapely" requirement (the unrelated PyPI library, written
 * by older CLI versions) with scrapely-python, and adds what is missing.
 */
export function ensureScrapyRequirements(content: string): { content: string; changes: string[] } {
    const changes: string[] = [];
    let hasSdk = false;
    let hasScrapy = false;
    const lines = content.split('\n').flatMap((line) => {
        const name = requirementName(line);
        if (name === 'scrapely') {
            changes.push(`Replaced "${line.trim()}" with ${PYPI_SDK_PACKAGE} in requirements.txt (PyPI "scrapely" is an unrelated package)`);
            if (hasSdk) return [];
            hasSdk = true;
            return [PYPI_SDK_PACKAGE];
        }
        if (name === PYPI_SDK_PACKAGE) hasSdk = true;
        if (name === 'scrapy') hasScrapy = true;
        return [line];
    });
    let result = lines.join('\n').trimEnd();
    if (!hasSdk) {
        result += `\n${PYPI_SDK_PACKAGE}`;
        changes.push(`Added ${PYPI_SDK_PACKAGE} to requirements.txt`);
    }
    if (!hasScrapy) {
        result += '\nscrapy';
        changes.push('Added scrapy to requirements.txt');
    }
    return { content: changes.length ? result.replace(/^\n+/, '') + '\n' : content, changes };
}

export async function initCommand(name?: string, options?: { dockerfile?: string; yes?: boolean }): Promise<void> {
    const cwd = process.cwd();

    // SECURITY: Validate optional directory name before joining
    if (name) {
        try {
            validateFilename(name);
        } catch (err) {
            console.error(chalk.red(`Error: Invalid directory name: ${(err as Error).message}`));
            process.exit(1);
        }
    }

    let targetDir: string;
    try {
        targetDir = name ? safeResolve(cwd, name) : cwd;
    } catch (err) {
        console.error(chalk.red(`Error: Invalid target directory: ${(err as Error).message}`));
        process.exit(1);
    }

    if (name && !existsSync(targetDir)) {
        mkdirSync(targetDir, { recursive: true });
    }

    // Scrapy project detection: wrap the existing project
    // with a Python Actor entrypoint instead of creating a Node.js starter.
    const isScrapyProject = existsSync(join(targetDir, 'scrapy.cfg'));


    const pkgPath = join(targetDir, 'package.json');
    if (existsSync(pkgPath) && !options?.yes) {
        // ask instead of silently skipping when a
        // package.json already exists. Non-interactive runs (no TTY) and
        // --yes keep the old skip behavior, so scripts/CI are unaffected.
        let proceed = false;
        if (process.stdout.isTTY) {
            const { answer } = await inquirer.prompt([
                {
                    type: 'confirm',
                    name: 'answer',
                    message: 'package.json already exists. Continue initializing an actor here anyway?',
                    default: false,
                },
            ]);
            proceed = answer;
        }
        if (!proceed) {
            console.log(chalk.yellow('Warning: package.json already exists. Skipping init.'));
            return;
        }
        console.log(chalk.yellow('Warning: package.json already exists. Keeping it (scripts and dependencies untouched).'));
    }

    // warn + confirm when the directory has files but does
    // not look like a Node.js or Python project. Empty directories (the normal
    // "scrapely init name" flow) skip this, as do --yes and non-TTY runs.
    const looksLikeProject = existsSync(pkgPath)
        || isScrapyProject
        || existsSync(join(targetDir, 'pyproject.toml'))
        || existsSync(join(targetDir, 'requirements.txt'));
    if (!looksLikeProject && !options?.yes && process.stdout.isTTY && readdirSync(targetDir).length > 0) {
        const { answer } = await inquirer.prompt([
            {
                type: 'confirm',
                name: 'answer',
                message: 'The current directory does not look like a Node.js or Python project. Continue?',
                default: true,
            },
        ]);
        if (!answer) return;
    }

    // Get actor name - skip prompt if --yes flag is set
    let actorName = name || 'my-actor';
    if (!options?.yes) {
        const { promptedName } = await inquirer.prompt([
            {
                type: 'input',
                name: 'promptedName',
                message: 'Actor name',
                default: name || 'my-actor',
                validate: validateActorName,
            },
        ]);
        actorName = promptedName;
    }

    // Build scrapely.json configuration
    const scrapelyConfig: Record<string, unknown> = {
        actorSpecification: 1,
        name: actorName,
        version: '0.0',
        buildTag: 'latest',
    };
    
    // Add dockerfile path if provided
    if (options?.dockerfile) {
        scrapelyConfig.dockerfile = options.dockerfile;
    }

    // Create scrapely.json unless the project already has an actor config
    // (.actor/actor.json, .actor/scrapely.json, scrapely.json or actor.json) —
    // a second config would shadow the existing one.
    const hasActorConfig = ACTOR_CONFIG_FILES.some((rel) => existsSync(join(targetDir, ...rel.split('/'))));
    if (!hasActorConfig) {
        writeFileSync(join(targetDir, 'scrapely.json'), JSON.stringify(scrapelyConfig, null, 2));
    }

    if (isScrapyProject) {
        const mainPyPath = join(targetDir, 'main.py');
        if (existsSync(mainPyPath)) {
            console.log(chalk.yellow('Warning: main.py already exists. Skipping Scrapy Actor wrapper generation.'));
        } else {
            writeFileSync(mainPyPath, SCRAPY_MAIN_PY);
            console.log(chalk.green('✓ Scrapy project detected (scrapy.cfg) - created main.py Actor wrapper'));
        }

        // Make sure the Scrapely SDK is declared as a dependency. Its PyPI name
        // is scrapely-python: the PyPI package "scrapely" is an unrelated
        // library with the same import name, which would shadow the SDK.
        const requirementsPath = join(targetDir, 'requirements.txt');
        if (existsSync(requirementsPath)) {
            const original = readFileSync(requirementsPath, 'utf-8');
            const { content, changes } = ensureScrapyRequirements(original);
            if (content !== original) {
                writeFileSync(requirementsPath, content);
                for (const change of changes) console.log(chalk.green(`✓ ${change}`));
            }
        } else {
            writeFileSync(requirementsPath, `${PYPI_SDK_PACKAGE}\nscrapy\n`);
            console.log(chalk.green('✓ Created requirements.txt'));
        }
    } else {
    // Create package.json for Node.js project. SECURITY: never overwrite an
    // existing one — `init` may legitimately be run inside an existing project
    // (with `-y`), and clobbering its package.json would destroy the project's
    // scripts, dependencies, and metadata.
    if (existsSync(pkgPath)) {
        console.log(chalk.yellow('Warning: package.json already exists. Keeping it (scripts and dependencies untouched).'));
        console.log(chalk.gray('  Add the SDK manually if missing: npm install scrapely'));
    } else {
        writeFileSync(pkgPath, JSON.stringify({
            name: actorName,
            version: '0.0.1',
            type: 'module',
            main: 'main.js',
            scripts: {
                start: 'node main.js',
            },
            dependencies: {
                scrapely: '*',
            },
        }, null, 2));
    }

    // main.js
    const mainPath = join(targetDir, 'main.js');
    if (!existsSync(mainPath)) {
        writeFileSync(mainPath, `import { Actor, PlaywrightCrawler, Dataset } from 'scrapely';

await Actor.init();

const input = await Actor.getInput() || { startUrls: ['https://example.com'] };

const crawler = new PlaywrightCrawler({
    launchContext: { useIncognitoPages: true },
    browserPoolOptions: { retireBrowserAfterPageCount: 1 },
    navigationTimeoutSecs: 120,
    maxConcurrency: 1,
    requestHandler: async ({ page, request, pushData }) => {
        const title = await page.title();
        console.log(\`[Crawled] \${request.url} -> \${title}\`);
        await pushData({ url: request.url, title });
    },
});

await crawler.run(input.startUrls);

await Actor.exit();
`);
    }
    }

    // .gitignore
    const gitignorePath = join(targetDir, '.gitignore');
    if (!existsSync(gitignorePath)) {
        writeFileSync(gitignorePath, `node_modules/
storage/
dist/
.env
.scrapely/
__pycache__/
*.pyc
.venv/
venv/
`);
    }

    // .actorignore (for excluding files from push)
    const actorignorePath = join(targetDir, '.actorignore');
    if (!existsSync(actorignorePath)) {
        writeFileSync(actorignorePath, `# Files to exclude from actor push
node_modules/
.git/
storage/
dist/
.env
*.log
.DS_Store
__pycache__/
*.pyc
.venv/
venv/
`);
    }

    console.log(chalk.green(`\n✓ Actor "${actorName}" initialized in ${name ? targetDir : 'current directory'}`));
    if (isScrapyProject) {
        console.log(chalk.gray('  Created: scrapely.json, main.py (Scrapy Actor wrapper), requirements.txt, .gitignore, .actorignore'));
        console.log(chalk.gray('\n  Next steps:'));
        console.log(chalk.gray('    pip install -r requirements.txt'));
    } else {
        console.log(chalk.gray('  Created: scrapely.json, package.json, main.js, .gitignore, .actorignore'));
        console.log(chalk.gray('\n  Next steps:'));
        console.log(chalk.gray('    npm install'));
    }
    console.log(chalk.gray('    scrapely push'));
    console.log(chalk.gray('    scrapely run'));
}
